// lib/lessonPlan/scheduledGeneration.test.ts
//
// Friday lesson-plan generation targets only schemes a teacher is actually
// using (lib/lessonPlan/scheduledGeneration.ts; audit F-16).
//
// No DB: repos.curriculum is faked for the two batched signal queries, and
// the runner's dependencies are injected (generateWeeklyPlans is counted so
// "no model calls" is observable).
//
// Run: npx tsx --experimental-test-module-mocks --test lib/lessonPlan/scheduledGeneration.test.ts
import { test, before, beforeEach, mock } from 'node:test'
import assert from 'node:assert/strict'
import type { WeeklyGenerationResult } from './types'

const NOW = Date.parse('2026-10-30T15:00:00Z') // a Friday, cron time
const daysAgo = (n: number) => new Date(NOW - n * 86_400_000).toISOString()

let taught: Array<{ sow_id: string; taught_date: string }> = []
let manual: Array<{ sow_id: string; created_at: string }> = []
const queries: string[] = []

mock.module('@/lib/repositories', {
  namedExports: {
    repos: {
      curriculum: {
        // Mirror the real queries' since-filters so the fake can't be looser than the DB.
        findTaughtPlansSince: async (ids: string[], since: string) => { queries.push('taught'); return taught.filter(t => ids.includes(t.sow_id) && t.taught_date >= since) },
        findManualGenerationsSince: async (ids: string[], since: string) => { queries.push('manual'); return manual.filter(m => ids.includes(m.sow_id) && m.created_at >= since) },
      },
    },
  },
})

let mod: typeof import('./scheduledGeneration')
before(async () => { mod = await import('./scheduledGeneration') })
beforeEach(() => { taught = []; manual = []; queries.length = 0 })

const OLD = daysAgo(60) // a scheme created long ago

// ── Eligibility ──────────────────────────────────────────────────────────────

test('1. a scheme the teacher is teaching from (lesson marked taught recently) is eligible', async () => {
  taught = [{ sow_id: 'active', taught_date: daysAgo(4).slice(0, 10) }]
  const inUse = await mod.findSchemesInUse([{ id: 'active', created_at: OLD }], NOW)
  assert.ok(inUse.has('active'))
})

test('2. an unused scheme (old, nothing taught, never generated by hand) is excluded', async () => {
  const inUse = await mod.findSchemesInUse([{ id: 'abandoned', created_at: OLD }], NOW)
  assert.equal(inUse.size, 0)
})

test('2b. use that has lapsed beyond the lookback no longer qualifies', async () => {
  taught = [{ sow_id: 'lapsed', taught_date: daysAgo(mod.SCHEDULED_PLAN_LOOKBACK_DAYS + 3).slice(0, 10) }]
  manual = [{ sow_id: 'lapsed', created_at: daysAgo(mod.SCHEDULED_PLAN_LOOKBACK_DAYS + 1) }]
  assert.equal((await mod.findSchemesInUse([{ id: 'lapsed', created_at: OLD }], NOW)).size, 0)
})

test('a teacher generating a week by hand, or a newly created scheme, counts as use', async () => {
  manual = [{ sow_id: 'manual', created_at: daysAgo(2) }]
  const inUse = await mod.findSchemesInUse([
    { id: 'manual', created_at: OLD },
    { id: 'brand-new', created_at: daysAgo(1) },
  ], NOW)
  assert.deepEqual([...inUse].sort(), ['brand-new', 'manual'])
})

test('5. teachers and schools stay isolated — one teacher\'s activity never makes another\'s scheme eligible', async () => {
  taught = [{ sow_id: 'teacher-A-school-1', taught_date: daysAgo(1).slice(0, 10) }]
  const inUse = await mod.findSchemesInUse([
    { id: 'teacher-A-school-1', created_at: OLD },
    { id: 'teacher-B-school-2', created_at: OLD },
  ], NOW)
  assert.deepEqual([...inUse], ['teacher-A-school-1'])
})

test('signals are fetched in two batched queries for the whole set — never per scheme', async () => {
  await mod.findSchemesInUse(Array.from({ length: 25 }, (_, i) => ({ id: `s${i}`, created_at: OLD })), NOW)
  assert.deepEqual(queries.sort(), ['manual', 'taught'])
})

// ── Runner ───────────────────────────────────────────────────────────────────

function deps(overrides: Partial<import('./scheduledGeneration').ScheduledGenerationDeps> = {}) {
  const calls: Array<{ sowId: string; authUserId: string; week: number }> = []
  const jobs: Array<Record<string, unknown>> = []
  const identityLookups: string[] = []
  const d: import('./scheduledGeneration').ScheduledGenerationDeps = {
    inUse: new Set(),
    authUserFor: async (teacherId) => { identityLookups.push(teacherId); return `auth-${teacherId}` },
    generateWeeklyPlans: async (sowId, authUserId, week) => { calls.push({ sowId, authUserId, week }); return { generated: 5, week: week + 1 } },
    recordJob: async (row) => { jobs.push(row) },
    ...overrides,
  }
  return { d, calls, jobs, identityLookups }
}

test('8. no eligible schemes → no model calls, no identity lookups, no job rows', async () => {
  const { d, calls, jobs, identityLookups } = deps()
  const out = await mod.runScheduledLessonPlanGeneration(
    [{ id: 'x', teacherId: 't1', latestWeek: 3 }, { id: 'y', teacherId: 't2', latestWeek: 0 }], d)
  assert.equal(calls.length, 0)
  assert.equal(jobs.length, 0)
  assert.equal(identityLookups.length, 0)
  assert.deepEqual(out.skipped.map(s => s.reason), ['not_in_use', 'not_in_use'])
})

test('3. a scheme whose teacher has no authoritative identity is excluded (fail closed), with no model call', async () => {
  const { d, calls } = deps({ inUse: new Set(['x']), authUserFor: async () => null })
  const out = await mod.runScheduledLessonPlanGeneration([{ id: 'x', teacherId: 'ghost', latestWeek: 1 }], d)
  assert.equal(calls.length, 0)
  assert.deepEqual(out.skipped, [{ sowId: 'x', reason: 'unresolved_teacher_identity' }])
})

test('5b. plans are generated under each scheme\'s OWN teacher, for that scheme\'s next week', async () => {
  const { d, calls } = deps({ inUse: new Set(['a', 'b']) })
  await mod.runScheduledLessonPlanGeneration([
    { id: 'a', teacherId: 'tA', latestWeek: 3 },
    { id: 'b', teacherId: 'tB', latestWeek: 0 },
  ], d)
  assert.deepEqual(calls, [
    { sowId: 'a', authUserId: 'auth-tA', week: 3 },
    { sowId: 'b', authUserId: 'auth-tB', week: 0 },
  ])
})

test('4/6. a re-run where plans already exist records a no-op, not a regeneration', async () => {
  const { d, jobs } = deps({
    inUse: new Set(['a']),
    generateWeeklyPlans: async () => ({ generated: 0, reason: 'already_generated' } as WeeklyGenerationResult),
  })
  const out = await mod.runScheduledLessonPlanGeneration([{ id: 'a', teacherId: 'tA', latestWeek: 3 }], d)
  assert.equal(out.results[0].result.reason, 'already_generated')
  assert.equal(jobs[0].error_message, 'skipped: already_generated')
})

test('7. partial success is recorded as partial; one scheme failing never stops the next', async () => {
  const { d, jobs } = deps({
    inUse: new Set(['partial', 'boom', 'ok']),
    generateWeeklyPlans: async (sowId) => {
      if (sowId === 'boom') throw new Error('all lessons failed')
      return sowId === 'partial'
        ? { generated: 3, failed: 2, failedLessons: [{ lessonNumber: 4, error: 'x' }, { lessonNumber: 5, error: 'y' }] }
        : { generated: 5 }
    },
  })
  const out = await mod.runScheduledLessonPlanGeneration([
    { id: 'partial', teacherId: 't', latestWeek: 1 },
    { id: 'boom', teacherId: 't', latestWeek: 1 },
    { id: 'ok', teacherId: 't', latestWeek: 1 },
  ], d)
  assert.equal(out.results.length, 2)
  assert.deepEqual(out.errors.map(e => e.sowId), ['boom'])
  assert.equal(jobs.find(j => j.sow_id === 'partial')?.error_message, 'partial: 2 lesson(s) failed')
  assert.equal(jobs.find(j => j.sow_id === 'boom')?.status, 'failed')
  assert.equal(jobs.find(j => j.sow_id === 'ok')?.error_message, null)
})

test('isSchemeInUse: the lookback boundary is inclusive and invalid dates never qualify', () => {
  const edge = new Date(NOW - mod.SCHEDULED_PLAN_LOOKBACK_DAYS * 86_400_000).toISOString()
  assert.equal(mod.isSchemeInUse({ createdAt: edge, latestTaughtDate: null, latestManualGeneration: null }, NOW), true)
  assert.equal(mod.isSchemeInUse({ createdAt: 'not-a-date', latestTaughtDate: null, latestManualGeneration: null }, NOW), false)
})
