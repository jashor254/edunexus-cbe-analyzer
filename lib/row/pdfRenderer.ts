// ─── Table page ───────────────────────────────────────────────────────────────

function buildTablePage(row: RecordOfWork): string {
  const entries = row.entries
  const n = entries.length

  // Pre-compute rowspans for STRAND and SUB-STRAND columns.
  // skipX[i] = true → this cell is absorbed by a rowspan above, omit it.
  const skipStrand:    boolean[] = new Array(n).fill(false)
  const strandSpan:    number[]  = new Array(n).fill(1)
  const skipSubstrand: boolean[] = new Array(n).fill(false)
  const substrandSpan: number[]  = new Array(n).fill(1)

  for (let i = 0; i < n; i++) {
    if (skipStrand[i]) continue

    // Strand run
    const strandName = entries[i].strand
    let sj = i + 1
    while (sj < n && entries[sj].strand === strandName) { skipStrand[sj] = true; sj++ }
    strandSpan[i] = sj - i

    // Sub-strand run (always a sub-range of the strand run)
    const subName = entries[i].sub_strand
    let sk = i + 1
    while (
      sk < n &&
      entries[sk].sub_strand === subName &&
      entries[sk].strand === strandName
    ) { skipSubstrand[sk] = true; sk++ }
    substrandSpan[i] = sk - i
  }

  const spanAttr = (span: number) =>
    span > 1 ? ` rowspan="${span}" class="merged-cell"` : ''

  const bodyRows = entries.map((e, i) => {
    const date          = getLessonDate(e.week_number, row.term, row.year)
    const strandCell    = skipStrand[i]    ? '' : `<td${spanAttr(strandSpan[i])}>${esc(e.strand)}</td>`
    const substrandCell = skipSubstrand[i] ? '' : `<td${spanAttr(substrandSpan[i])}>${esc(e.sub_strand)}</td>`

    return `<tr class="${statusClass(e.status)}">
      <td class="center">${e.week_number}</td>
      <td class="center">${e.lesson_number}</td>
      <td class="center date-cell">${esc(date)}</td>
      ${strandCell}
      ${substrandCell}
      <td>${bullets(e.learning_outcomes)}</td>
      <td>${bullets(e.key_inquiry_questions)}</td>
      <td>${bullets(e.activities_summary)}</td>
      <td>${bullets(e.learning_resources)}</td>
      <td class="center assess-cell">—</td>
      <td class="remarks-cell">${esc(e.remarks)}</td>
      <td class="sig-cell"></td>
    </tr>`
  }).join('')

  // Footer counts
  const total     = n
  const completed = entries.filter(e => e.status === 'completed').length
  const carried   = entries.filter(e => e.status === 'carried_forward').length

  return `
  <div class="sow-page">
    <div class="sow-header">
      <strong>${esc(row.school)}</strong> &nbsp;|&nbsp;
      ${esc(row.learning_area)} &nbsp;|&nbsp;
      ${esc(row.grade)} &nbsp;|&nbsp;
      Term ${esc(row.term)} ${esc(row.year)} &nbsp;|&nbsp;
      ${esc(row.teacher_name)}
    </div>
    <table>
      <thead>
        <tr>
          <th style="width:3%">WK</th>
          <th style="width:3%">LSN</th>
          <th style="width:6%">DATE</th>
          <th style="width:8%">STRAND</th>
          <th style="width:9%">SUB-STRAND</th>
          <th style="width:12%">LEARNING OUTCOMES</th>
          <th style="width:11%">KEY INQUIRY QUESTIONS</th>
          <th style="width:14%">LEARNING EXPERIENCES / ACTIVITIES</th>
          <th style="width:10%">LEARNING RESOURCES</th>
          <th style="width:7%">ASSESSMENT</th>
          <th style="width:10%">REMARKS / REFLECTION</th>
          <th style="width:7%">SIGNATURE</th>
        </tr>
      </thead>
      <tbody>
        ${bodyRows}
      </tbody>
    </table>
    <div class="sow-footer">
      Total Lessons: <strong>${total}</strong> &nbsp;|&nbsp;
      Completed: <strong>${completed}</strong> &nbsp;|&nbsp;
      Carried Forward: <strong>${carried}</strong>
      &nbsp;·&nbsp; EduNexus · KICD Aligned
    </div>
  </div>`
}

