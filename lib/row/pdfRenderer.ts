// ─── Public API ───────────────────────────────────────────────────────────────

export function generateROWHTML(row: RecordOfWork): string {
  const cover = buildCoverPage(row)
  const table = buildTablePage(row)

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8"/>
  <title>Record of Work — ${esc(row.learning_area)} ${esc(row.grade)} Term ${esc(row.term)} ${esc(row.year)}</title>
  <style>${CSS}</style>
</head>
<body>
  <div class="no-print" style="text-align:right;padding:12px 16px;">
    <button onclick="window.print()"
      style="background:#1e3a5f;color:#fff;border:none;padding:10px 22px;border-radius:6px;
             font-size:10pt;cursor:pointer;font-weight:bold;">
      Print / Save as PDF
    </button>
  </div>
  ${cover}
  ${table}
</body>
</html>`
}

export function downloadROWAsPDF(row: RecordOfWork): void {
  const html = generateROWHTML(row)
  const win = window.open('', '_blank')
  if (!win) return
  win.document.write(html)
  win.document.close()
  win.focus()
  setTimeout(() => {
    win.print()
    win.close()
  }, 800)
}
