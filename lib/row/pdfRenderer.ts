// lib/row/pdfRenderer.ts
// HTML → browser print renderer for Record of Work download.
// Produces: Page 1 = cover page, Page 2+ = A4 landscape ROW table.
// Mirrors lib/sow/pdfRenderer.ts exactly in structure and CSS variables.

// ─── Types ────────────────────────────────────────────────────────────────────

export interface ROWEntry {
  week_number:           number
  lesson_number:         number
  strand:                string
  sub_strand:            string
  learning_outcomes:     string | string[]
  key_inquiry_questions: string | string[]
  learning_resources:    string | string[]
  activities_summary:    string | string[]
  status:                'completed' | 'not_completed' | 'carried_forward'
  remarks:               string
}

export interface RecordOfWork {
  teacher_name: string
  tsc_number:   string
  school:       string
  grade:        string
  learning_area: string
  term:         number | string
  year:         number | string
  entries:      ROWEntry[]
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

function esc(s: string | number | undefined | null): string {
  if (s == null) return '—'
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function bullets(value: string | string[] | undefined | null): string {
  if (!value) return '—'
  const items = Array.isArray(value) ? value : [value]
  if (!items.length) return '—'
  return `<ul>${items.map(i => `<li>${esc(i)}</li>`).join('')}</ul>`
}

// Term start dates: [month (0-based), day]
const TERM_STARTS: Record<string, [number, number]> = {
  '1': [0, 6],  // Jan 6
  '2': [4, 5],  // May 5
  '3': [8, 1],  // Sep 1
}

function getLessonDate(
  weekNumber: number,
  term: number | string,
  year: number | string
): string {
  const start = TERM_STARTS[String(term)]
  if (!start) return `Wk ${weekNumber}`
  const base = new Date(Number(year), start[0], start[1])
  base.setDate(base.getDate() + (weekNumber - 1) * 7)
  return base.toLocaleDateString('en-KE', { day: 'numeric', month: 'short' })
}

function statusClass(status: ROWEntry['status']): string {
  if (status === 'not_completed')  return 'row-not-completed'
  if (status === 'carried_forward') return 'row-carried'
  return ''
}

