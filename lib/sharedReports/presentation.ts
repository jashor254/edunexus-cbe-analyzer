import type { SharedReportProvenance } from './read'

// What the public report page may truthfully say about where a report came
// from. Content supplied by the sharer must never be presented as an
// EduNexus-generated assessment, nor as "reviewed by parent"/"actual scores".
export type ReportOriginCopy = {
  reportLabel: string
  byline: string
  footer: string
  disclaimer: string
}

const ADVISORY = 'All recommendations are advisory — final educational decisions rest with parents, teachers, and students.'

export function reportOriginCopy(provenance: SharedReportProvenance, createdDate: string): ReportOriginCopy {
  if (provenance === 'server_generated') {
    return {
      reportLabel: 'Learner Intelligence Report',
      byline: `Generated by EduNexus from available learner evidence · ${createdDate}`,
      footer: 'Report generated by EduNexus from available learner evidence · edunexus.co.ke',
      disclaimer: `This report reflects the learner's recorded assessment evidence. ${ADVISORY}`,
    }
  }
  return {
    reportLabel: 'Shared Learner Report',
    byline: `Shared via EduNexus · content supplied by the sender and not verified by EduNexus · ${createdDate}`,
    footer: 'Shared via EduNexus · not verified by EduNexus · edunexus.co.ke',
    disclaimer: `The content of this report was supplied by the person who shared it; EduNexus has not independently verified it. ${ADVISORY}`,
  }
}
