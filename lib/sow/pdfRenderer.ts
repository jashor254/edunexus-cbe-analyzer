export function downloadSOWAsPDF(data: SOWPreviewData, colConfig: ColConfig): void {
  const html = generateSOWHTML(data, colConfig)
  const win = window.open('', '_blank')
  if (!win) return
  win.document.write(html)
  win.document.close()
  win.focus()
  setTimeout(() => {
    win.print()
    win.close()
  }, 800)
}
