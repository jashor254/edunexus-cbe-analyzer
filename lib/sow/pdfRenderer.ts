// lib/sow/pdfRenderer.ts
// HTML → browser print renderer for SOW download.
// Produces: Page 1 = cover page, Page 2+ = A4 landscape SOW table.

import type { SOWPreviewData, GeneratedLesson, BreakItem, CurriculumMode } from './types'

export interface ColConfig {
  col3: string
  col4: string
  col5: string
  col6: string
  col7?: string
  col8: string
  col9: string
  col10?: string
  hasInquiryQuestions: boolean
}

export function getColumnConfig(mode: CurriculumMode): ColConfig {
  if (mode === '844_form3' || mode === '844_form4') {
    return {
      col3: 'TOPIC',
      col4: 'SUB-TOPIC',
      col5: 'OBJECTIVES',
      col6: 'T/L ACTIVITIES',
      col8: 'T/L AIDS',
      col9: 'REFERENCE',
      col10: 'REMARKS',
      hasInquiryQuestions: false,
    }
  }
  return {
    col3: 'STRAND',
    col4: 'SUB-STRAND',
    col5: 'LESSON LEARNING OUTCOMES',
    col6: 'LEARNING EXPERIENCES',
    col7: 'KEY INQUIRY QUESTIONS',
    col8: 'LEARNING RESOURCES',
    col9: 'ASSESSMENT METHODS',
    col10: 'REFLECTION',
    hasInquiryQuestions: true,
  }
}

function esc(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function bullets(items: string[]): string {
  if (!items?.length) return '—'
  return `<ul>${items.map(i => `<li>${esc(i)}</li>`).join('')}</ul>`
}

function breakDetail(b: BreakItem): string {
  const wk = b.startWeek === b.endWeek
    ? `Wk ${b.startWeek}`
    : `Wk ${b.startWeek}–${b.endWeek}`
  return `${wk} · L${b.startLesson}–L${b.endLesson}`
}

